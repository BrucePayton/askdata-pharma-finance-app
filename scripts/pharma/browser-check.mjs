import { chromium } from '../../frontend/node_modules/playwright/index.mjs';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const state=JSON.parse(fs.readFileSync(path.join(os.homedir(),'.local/state/askdata-pharma/resources.json'),'utf8'));
const browser=await chromium.launch({headless:true});const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto((process.env.PHARMA_BASE_URL||'http://localhost:18190')+'/pharma-finance/');
await page.getByLabel('账号',{exact:true}).fill(state.demo_user.username);
await page.getByLabel('密码',{exact:true}).fill(state.demo_user.password);
await page.getByRole('button',{name:'进入工作空间'}).click();
await page.getByRole('heading',{name:'看清经营变化，追溯每一项财务判断'}).waitFor({timeout:90000});
await page.getByRole('button',{name:'选择分析',exact:true}).first().click();
await page.getByRole('button',{name:'计算与查看明细'}).click();
await page.getByText('抵销后收入',{exact:true}).waitFor({timeout:90000});
await page.screenshot({path:'/tmp/pharma-desktop.png',fullPage:true});
await page.getByRole('button',{name:'知识依据',exact:true}).click();
if(await page.getByRole('link',{name:'查看原始来源 ↗'}).count()!==3)throw new Error('Missing source links');
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'场景中心',exact:true}).click();
await page.screenshot({path:'/tmp/pharma-mobile.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2))throw new Error('Mobile overflow');
if(errors.length)throw new Error(errors.join('\n'));
console.log('Browser acceptance passed: login, scope, calculation, citations, desktop/mobile');
await browser.close();
